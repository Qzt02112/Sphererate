def checkpoint_dynamics(checkpoint_path: Path) -> tuple[np.ndarray, ...]:
    checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
    state = checkpoint["model"]
    alpha_inc = torch.nn.functional.softplus(state["semantic_alpha_deltas"])
    alpha = 1.0 - torch.exp(-torch.cumsum(alpha_inc, dim=0))
    east_inc = torch.nn.functional.softplus(state["reachability_beta_deltas"])
    east = torch.flip(torch.cumsum(torch.flip(east_inc, dims=(0,)), dim=0), dims=(0,))
    north_inc = torch.nn.functional.softplus(state["reachability_north_beta_deltas"])
    north = torch.flip(
        torch.cumsum(torch.flip(north_inc, dims=(0,)), dim=0), dims=(0,)
    )
    maximum_offset_rad = math.radians(
        float(checkpoint["config"]["model"]["maximum_reachability_offset_deg"])
    )
    offsets = maximum_offset_rad * torch.tanh(
        state["reachability_offsets_unconstrained"]
    )
    offsets = torch.rad2deg(offsets)
    return tuple(item.detach().cpu().numpy() for item in (alpha, east, north, offsets))


def mean_std_text(values: np.ndarray, decimals: int = 3) -> str:
    mean = float(np.mean(values))
    std = float(np.std(values, ddof=1))
    return f"{mean:.{decimals}f}$\\pm${std:.{decimals}f}"


