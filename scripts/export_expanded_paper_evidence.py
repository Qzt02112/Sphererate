def load_json(relative: str) -> dict:
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


def write_table(name: str, text: str) -> None:
    path = TABLE_DIR / name
    path.write_text(
        "% AUTO-GENERATED by scripts/export_expanded_paper_evidence.py.\n"
        "% Do not edit numerical cells by hand.\n"
        + text.strip()
        + "\n",
        encoding="utf-8",
    )


def f3(value: float) -> str:
    """Format a paper value with the leading zero required by IEEE style."""
    return f"{value:.3f}"


def signed(value: float, decimals: int = 3) -> str:
    if abs(value) < 0.5 * 10 ** (-decimals):
        value = 0.0
    return f"{value:+.{decimals}f}"


def ci_cell(
    item: dict, *, mean_key: str = "mean_improvement", decimals: int = 3
) -> str:
    mean = float(item[mean_key])
    low = float(item["ci95_low"])
    high = float(item["ci95_high"])
    return (
        f"{signed(mean, decimals)} "
        f"[{signed(low, decimals)},{signed(high, decimals)}]"
    )


def per_horizon_mean(method: dict, horizon: str) -> dict:
    row = method["per_horizon"][horizon]
    return row["mean"] if "mean" in row else row


