def read_primary_content_rows() -> dict:
    """Return method/content/horizon/metric -> values over seeds."""
    path = ROOT / "reports" / "standard_split_primary_test" / "per_content.csv"
    nested: dict = defaultdict(
        lambda: defaultdict(lambda: defaultdict(lambda: defaultdict(list)))
    )
    with path.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            horizon = f"{float(row['horizon_s']):g}"
            for metric in METRICS:
                nested[row["method"]][row["content_id"]][horizon][metric].append(
                    float(row[metric])
                )
    return nested


def bootstrap_all_horizon(rows: dict, baseline: str, seed: int = 20260711) -> dict:
    contents = sorted(rows["v12c"])
    rng = np.random.default_rng(seed)
    samples = rng.integers(0, len(contents), size=(10_000, len(contents)))
    result = {}
    for metric in METRICS:
        values = []
        for content in contents:
            deltas = []
            for horizon in HORIZONS:
                ours = float(np.mean(rows["v12c"][content][horizon][metric]))
                base = float(np.mean(rows[baseline][content][horizon][metric]))
                deltas.append(base - ours if metric == "kld_sph" else ours - base)
            values.append(float(np.mean(deltas)))
        values_array = np.asarray(values, dtype=np.float64)
        boot = values_array[samples].mean(axis=1)
        result[metric] = {
            "mean": float(values_array.mean()),
            "ci95_low": float(np.quantile(boot, 0.025)),
            "ci95_high": float(np.quantile(boot, 0.975)),
        }
    return result


